import assert from 'node:assert/strict'
import { join } from 'node:path'
/** Runs on the authenticated real component fixture; every gameplay action uses visible controls. */
export async function checkContentUI({ page, inspect, ready, currentFrame, drag, qa, checks }) {
  await page.getByRole('combobox', { name: '选择角色' }).selectOption('bluewhale')
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await drag({ x: 180, y: 425 })
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await page.evaluate(() => window.__villageHostFixture.flush())
  const originalFrame = currentFrame()
  await page.getByRole('button', { name: '展开小院', exact: true }).click()
  assert.equal(currentFrame(), originalFrame)
  await page.getByRole('tab', { name: '心愿', exact: true }).click()
  await page.getByRole('button', { name: '请一位朋友入住', exact: true }).click()
  await page.getByRole('button', { name: '邀请同桌', exact: true }).click()
  await page.waitForFunction(() => !!window.__villageHostFixture.inspect().world.activeEvent)
  const invited = (await inspect()).world
  assert.equal(invited.activeEvent.food, 'tea'); assert.equal(invited.journal.length, 0)
  await page.reload()
  await page.getByRole('button', { name: '打开 AI 小院', exact: true }).click(); await ready()
  assert.deepEqual((await inspect()).world, invited)
  await page.getByRole('button', { name: '展开小院', exact: true }).click()
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await page.waitForFunction(() => window.__villageHostFixture.inspect().world.activeEvent?.phase === 'talking', {}, { timeout: 60000 })
  await page.waitForTimeout(550)
  await page.locator('.village-card').screenshot({ path: join(qa, 'v04-tea-expanded.png') })
  await page.waitForFunction(() => window.__villageHostFixture.inspect().world.journal.length === 1, {}, { timeout: 15000 })
  await page.getByRole('button', { name: '暂停', exact: true }).click(); await page.evaluate(() => window.__villageHostFixture.flush())
  let world = (await inspect()).world
  assert.equal(world.activeEvent, null); assert.deepEqual(world.progress.unlocked, ['wind-chime'])
  assert.equal(world.decorations.windChime.slot, null)
  await page.getByRole('tab', { name: '手账', exact: true }).click()
  await page.getByRole('heading', { name: '今天，我们坐到了一起' }).waitFor()
  await page.locator('.village-card').screenshot({ path: join(qa, 'v04-journal.png') })
  await page.getByRole('tab', { name: '布置', exact: true }).click()
  await page.getByRole('button', { name: '选择挂点', exact: true }).click()
  await page.getByRole('button', { name: '门旁', exact: true }).click()
  assert.equal((await inspect()).world.decorations.windChime.slot, null)
  await page.keyboard.press('Escape')
  assert.equal((await inspect()).world.decorations.layoutRevision, 0)
  for (const [label, slot] of [['窗边', 'window'], ['门旁', 'door'], ['院墙', 'wall']]) {
    await page.getByRole('button', { name: '选择挂点', exact: true }).click()
    await page.getByRole('button', { name: label, exact: true }).click()
    await page.getByRole('button', { name: '确认摆放', exact: true }).click()
    await page.waitForFunction(slot => window.__villageHostFixture.inspect().world.decorations.windChime.slot === slot, slot)
    await page.locator('.village-card').screenshot({ path: join(qa, `v04-bell-${slot}.png`) })
  }
  world = (await inspect()).world
  assert.equal(world.decorations.layoutRevision, 3); assert.equal(world.journal.length, 1)
  const frame = currentFrame()
  await page.getByRole('button', { name: '小院设置', exact: true }).click()
  await page.getByRole('combobox', { name: '界面主题', exact: true }).selectOption('dark')
  await page.waitForFunction(() => !window.__villageHostFixture.inspect().preferencesSaving)
  await page.getByRole('checkbox', { name: '减少动态', exact: true }).click()
  await page.waitForFunction(() => window.__villageHostFixture.inspect().preferences.reducedMotion && !window.__villageHostFixture.inspect().preferencesSaving)
  await page.getByRole('combobox', { name: '语言', exact: true }).selectOption('en')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  assert.equal(currentFrame(), frame)
  await page.locator('.village-card').screenshot({ path: join(qa, 'v04-dark-english.png') })
  await page.setViewportSize({ width: 800, height: 600 })
  await page.waitForTimeout(150)
  assert.equal(currentFrame(), frame)
  const bounds = await page.locator('.village-card').boundingBox()
  assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.width <= 800 && bounds.height <= 600)
  await page.locator('.village-card').screenshot({ path: join(qa, 'v04-800x600.png') })
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.getByRole('button', { name: 'Compact courtyard', exact: true }).click()
  assert.equal(currentFrame(), frame)
  await page.locator('.village-card').screenshot({ path: join(qa, 'v04-compact-dark.png') })
  await page.reload(); await page.getByRole('button', { name: '打开 AI 小院', exact: true }).click(); await ready()
  assert.deepEqual((await inspect()).world, world)
  assert.equal((await inspect()).preferences.theme, 'dark'); assert.equal((await inspect()).preferences.language, 'en')
  assert.equal((await inspect()).preferences.reducedMotion, true)
  await page.getByRole('tab', { name: 'Journal', exact: true }).click()
  await page.getByRole('heading', { name: 'Today, we shared a table' }).waitFor()
  checks.push('0.4 visible controls: saved invitation resumes after reload; two-seat tea completes once; journal and bell unlock atomically; all three decor slots, draft Escape rollback; one frame across expanded/compact/800x600; persisted dark/en/reduced-motion settings and exact cold world restore')
}
